#ifndef DHT11_H
#define DHT11_H
/* =============================================================
 * dht11.h —— DHT11 温湿度传感器驱动（单总线，DATA 接 PB0）
 * 仅负责协议流程与校验；线级时序在 BSP/bsp_onewire.c
 * ============================================================= */
#include <stdint.h>
/* 读一次 DHT11。返回 1 = 成功（校验和也正确），返回 0 = 失败 */
uint8_t DHT11_Read(void);
/* ---- 诊断信息：既给串口打印用，也给 OLED 显示用 ----
 * 全部通过只读访问函数暴露，驱动内部状态保持 static、外部不可写 */
uint8_t  DHT_RawByte(uint8_t idx);  /* 最近一次读到的第 idx 个原始字节(0~4) */
uint8_t  DHT_Error(void);           /* 0 = 成功；非 0 = 失败发生在第几步 */
uint32_t DHT_OkCount(void);         /* 累计成功次数 */
uint32_t DHT_FailCount(void);       /* 累计失败次数 */
/* g_dht_err 编号含义：
 *   1 = 等不到 DHT11 拉低（没应答，多半是接线问题）
 *   2 = 等不到它把线放开
 *   3 = 等不到应答高电平结束
 *   4 = 读数据位时等不到高电平（时序被破坏）
 *   5 = 读数据位时等不到低电平
 *   6 = 数据读全了，但校验和不匹配（数据不可信） */
#endif /* DHT11_H */
