#ifndef DHT11_FRAME_H
#define DHT11_FRAME_H
/* =============================================================
 * dht11_frame.h —— DHT11 的「帧解析」（纯逻辑，无硬件依赖）
 *
 * 为什么要把这部分从 dht11.c 里拆出来：
 *   dht11.c 含时序驱动，必须真的操作 GPIO、跑微秒延时，在 PC 上没法
 *   编译运行；但「一串 40 位怎么解成温湿度」纯粹是位运算，与硬件无关。
 *   把两者分开之后，解析部分能在 PC 上喂已知帧做单元测试 ——
 *   校验和判据、负温符号位这些最容易写错的地方，反而正好覆盖到了。
 *
 * 帧格式（40 位 = 5 字节，高位在前）：
 *   raw[0] 湿度整数   raw[1] 湿度小数
 *   raw[2] 温度整数   raw[3] 温度小数
 *   raw[4] 校验和 = 前 4 字节之和，取最低 8 位
 * ============================================================= */
#include <stdint.h>

#define DHT_FRAME_LEN 5U   /* 一帧固定 5 字节 */

/* 校验一帧是否可信。返回 1 = 校验和正确，返回 0 = 数据不可信 */
uint8_t DHT_CheckSum(const uint8_t raw[DHT_FRAME_LEN]);

/* 解出温度，返回「放大 10 倍」的整数（256 表示 25.6 °C）。
 * 负温由「温度整数」字节的最高位标记，此时取低 7 位再取负。 */
int16_t DHT_DecodeTemp(const uint8_t raw[DHT_FRAME_LEN]);

/* 解出湿度，返回「放大 10 倍」的整数（650 表示 65.0 %） */
int16_t DHT_DecodeHumi(const uint8_t raw[DHT_FRAME_LEN]);

#endif /* DHT11_FRAME_H */
